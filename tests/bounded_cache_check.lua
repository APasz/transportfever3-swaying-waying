local cache = dofile("content/swaying_waying/bounded_cache.lua")
local values = cache.create(2)
local first = { history = 1.25 }
cache.put(values, 1, first)
cache.put(values, 2, { history = 1 })
assert(cache.get(values, 1) == first)
cache.put(values, 3, { history = 0.7 })
assert(cache.get(values, 2) == nil, "only the least recently used entry is evicted")
assert(cache.get(values, 1) == first, "an unrelated insertion preserves active state")
assert(values.count == 2)
cache.put(values, 1, { history = 1.1 })
assert(cache.get(values, 1).history == 1.1)
for key = 4, 100 do
	cache.put(values, key, { history = key })
	assert(cache.get(values, 1).history == 1.1, "a frequently used entry survives sustained cache pressure")
end
assert(values.count == 2, "storage remains bounded")
local strings = cache.create(1)
cache.put(strings, "model-a", false)
assert(cache.get(strings, "model-a") == false, "false is a cached value")
cache.put(strings, "model-b", true)
assert(cache.get(strings, "model-a") == nil and cache.get(strings, "model-b") == true)
assert(not pcall(cache.create, 0), "invalid capacities fail explicitly")
local timed = cache.create(16)
cache.configure(timed, 16, 1000)
cache.advance(timed, 0)
for key = 1, 16 do
	assert(cache.put(timed, key, key))
end
cache.advance(timed, 1000)
assert(timed.entries[16], "incremental expiry leaves entries for lazy removal")
assert(cache.put(timed, 16, "renewed"), "writes renew expired entries")
assert(cache.get(timed, 16) == "renewed", "a successful write must retain its value")
cache.advance(timed, 1999)
assert(cache.get(timed, 16) == "renewed", "renewal resets the retention clock")
assert(not pcall(cache.configure, timed, 16, math.huge), "retention must be finite")
assert(not pcall(cache.configure, timed, 16, 1000.5), "retention uses whole milliseconds")
print("Bounded cache checks passed")
